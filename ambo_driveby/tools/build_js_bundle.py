#!/usr/bin/env python3
"""Vendor and adapt the upstream macroquad JS bundle.

The upstream bundle (macroquad/js/mq_js_bundle.js) is a classic script that
binds to a hard-coded `#glcanvas` element and keeps all of its state (WebGL
context, wasm instance, event handlers) in module scope. That means a single
copy of the bundle can only ever drive one canvas.

This script downloads that bundle and wraps it in a factory so that the
exported `load(wasmPath, canvasId)` creates a fully independent macroquad
instance for the canvas with the given id (or `#id`/`.selector`, or the
element itself). A page can therefore host several canvases while sharing one
`mq_js_bundle.js` file.

Run `just update-js-bundle` to regenerate assets/mq_js_bundle/mq_js_bundle.js.
"""

import hashlib
import pathlib
import sys
import urllib.request

UPSTREAM_URL = "https://raw.githubusercontent.com/not-fl3/macroquad/master/js/mq_js_bundle.js"
ROOT = pathlib.Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "assets" / "mq_js_bundle" / "mq_js_bundle.js"

# Exact snippets from the upstream bundle that have to change. Each one must
# match exactly once, otherwise upstream changed shape and the patches (and the
# wrapper below) need to be reviewed.
PATCHES = [
    # The canvas is now the first argument of load() instead of a hard-coded
    # element.
    (
        'const version=2,canvas=document.querySelector("#glcanvas");',
        "const version=2;",
    ),
    # Do not steal focus when an instance is created: several instances on one
    # page would fight over it.
    (
        "canvas.focus(),",
        "",
    ),
    # window.onresize can only hold one handler, so the last instance loaded
    # would win and earlier canvases would stop resizing. Every instance needs
    # to listen for itself.
    (
        "window.onresize=function(){resize(canvas,wasm_exports.resize)}",
        'window.addEventListener("resize",function(){resize(canvas,wasm_exports.resize)})',
    ),
    # `load` is the name of the exported entry point now, rename the upstream
    # `load(wasmPath)` it wraps.
    (
        "function load(e){var t=fetch(e);",
        "function start(e){var t=fetch(e);",
    ),
]

