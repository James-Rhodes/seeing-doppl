WRAPPER_TAIL = '''
    return start(wasm_path);
}
'''


def fetch(url: str) -> str:
    request = urllib.request.Request(url, headers={"User-Agent": "macroquad-template"})
    with urllib.request.urlopen(request) as response:
        return response.read().decode("utf-8")


def apply_patches(source: str) -> str:
    for old, new in PATCHES:
        count = source.count(old)
        if count != 1:
            sys.exit(
                "error: expected exactly one occurrence of:\n"
                f"  {old!r}\n"
                f"but found {count}. The upstream bundle changed shape; "
                "review tools/build_js_bundle.py."
            )
        source = source.replace(old, new)
    return source


def main() -> None:
    upstream = fetch(UPSTREAM_URL)
    digest = hashlib.sha256(upstream.encode("utf-8")).hexdigest()

    bundle = (
        HEADER.format(url=UPSTREAM_URL, sha256=digest)
        + WRAPPER_HEAD
        + apply_patches(upstream)
        + WRAPPER_TAIL
    )

    OUTPUT.write_text(bundle)
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(bundle)} bytes, upstream {digest})")


if __name__ == "__main__":
    main()
